export function drawHead(
  c: CanvasRenderingContext2D,
  atlas: HTMLImageElement,
  id: number,
  x: number,
  y: number,
  size: number,
) {
  const cw = atlas.naturalWidth / 4,
    ch = atlas.naturalHeight / 2,
    sx = Math.round((id % 4) * cw),
    sy = Math.round(Math.floor(id / 4) * ch),
    ex = Math.round(((id % 4) + 1) * cw),
    ey = Math.round((Math.floor(id / 4) + 1) * ch);
  c.save();
  c.beginPath();
  outlines[id].forEach(([u, v], i) =>
    i ? c.lineTo(x + u * size, y + v * size) : c.moveTo(x + u * size, y + v * size),
  );
  c.closePath();
  c.clip();
  c.imageSmoothingEnabled = true;
  c.drawImage(atlas, sx, sy, ex - sx, ey - sy, x, y, size, size);
  c.restore();
}
